#pragma once
#include <string>

// ===========================================================================
// File: UIContext.h
//
// 【役割】UIシステムの「共通言語」定義ファイル
//
// 【解説】
// マウスの入力情報（座標やクリック状態）や、ドラッグ＆ドロップで
// 受け渡すデータの形など、システム全体で共有するデータ構造を定義しています。
// ロジック（処理）は持たず、データの型（入れ物）だけを決めています。
// ===========================================================================


// ---------------------------------------------------------------------------
// Struct: UIMouseState
// 役割: UIシステムに渡すためのマウス入力情報
// ---------------------------------------------------------------------------
struct UIMouseState {
    float x;          // マウスカーソルX座標
    float y;          // マウスカーソルY座標
    bool  isDown;     // 左クリック中（押しっぱなし）
    bool  isPressed;  // 今フレーム押された瞬間 (Trigger)
    bool  isReleased; // 今フレーム離された瞬間 (Release)
};

// ---------------------------------------------------------------------------
// Struct: DragPayload
// 役割: ドラッグ＆ドロップ操作で運ばれるデータ
// ---------------------------------------------------------------------------
struct DragPayload {
    std::string      type;          // データの種類識別子（例: "ATTACHMENT", "ITEM"）
    void            *data;          // 実データへのポインタ（void*で汎用化）
    class UIElement *sourceElement; // ドラッグを開始した元のUI要素
};